def h2r(h): h=h.lstrip('#'); return [int(h[i:i+2],16) for i in (0,2,4)]
def r2h(c): return '#%02x%02x%02x'%tuple(max(0,min(255,round(v))) for v in c)
def mix(a,b,t): # t of b
    a,b=h2r(a),h2r(b); return r2h([x+(y-x)*t for x,y in zip(a,b)])
def rgba(h,a): r=h2r(h); return f'rgba({r[0]}, {r[1]}, {r[2]}, {a})'
W,K='#ffffff','#000000'

